import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(root + '/package.json');
const { build, preview } = await import(pathToFileURL(require.resolve('vite')).href);
const { chromium } = require('@playwright/test');
const artifacts = mkdtempSync(join(tmpdir(), 'vision-tts-ui-'));
console.log('Test artifacts:', artifacts);
const outDir = join(artifacts, 'dist');
await build({ root, configFile: false, envDir: false, build: { outDir, emptyOutDir: true, chunkSizeWarningLimit: 1800, rollupOptions: { onwarn(warning, warn) { if (warning.code !== 'MODULE_LEVEL_DIRECTIVE') warn(warning); } } } });
const server = await preview({ root, configFile: false, envDir: false, build: { outDir }, preview: { host: '127.0.0.1', port: 5179, strictPort: true } });
let browser;
const checks = [];
function check(name, passed) { if (!passed) throw new Error(name); checks.push(name); }
try {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 950 } });
  const writes = [];
  await context.route('**/api/**', route => {
    if (route.request().method() !== 'GET') writes.push(route.request().url());
    return route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"isolated UI test"}' });
  });
  let available = false;
  let mode = 'success';
  const submitted = [];
  const wav = Buffer.alloc(44 + 48000);
  wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16,16); wav.writeUInt16LE(1,20); wav.writeUInt16LE(1,22);
  wav.writeUInt32LE(24000,24); wav.writeUInt32LE(48000,28); wav.writeUInt16LE(2,32); wav.writeUInt16LE(16,34);
  wav.write('data',36); wav.writeUInt32LE(48000,40);
  for (let i=0;i<24000;i++) wav.writeInt16LE(Math.round(Math.sin(i*.05)*4000),44+i*2);
  await context.route('**/api/tts/status', route => route.fulfill({json:{available,busy:false,model:'qwen3-tts-flash-realtime',message:'合成服务未配置（隔离测试）'}}));
  await context.route('**/api/tts/synthesize', async route => {
    submitted.push(route.request().postDataJSON());
    const responseMode = mode;
    if (responseMode === 'delayed') await new Promise(resolve => setTimeout(resolve, 1500));
    if (responseMode === 'failure') return route.fulfill({status:429,json:{detail:'测试：合成请求受限'}});
    if (responseMode === 'bad-audio') return route.fulfill({contentType:'audio/wav',body:Buffer.from('not wav')});
    await route.fulfill({contentType:'audio/wav',body:wav}).catch(()=>{});
  });
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5179/#/apps');
  await page.getByRole('button', { name: '打开语音合成体验', exact: true }).click();
  await page.getByRole('heading', { name: '语音合成体验', exact: true }).waitFor();
  check('Application hub opens TTS page', page.url().endsWith('#/tts'));
  await page.screenshot({ path: join(artifacts, 'desktop.png'), fullPage: true });
  await page.getByText('合成服务未配置（隔离测试）', { exact: true }).waitFor();
  check('Synthesis explicitly unavailable', await page.getByRole('button', { name: '合成语音', exact: true }).isDisabled());
  for (const name of ['播放语音', '下载音频']) check(`${name} unavailable without audio`, await page.getByRole('button', { name, exact: true }).isDisabled());
  await page.getByLabel('选择音色', { exact: true }).selectOption({ label: '活力男声 · 晨煦' });
  check('Voice selection editable', await page.getByLabel('选择音色', { exact: true }).inputValue() === 'Ethan');
  await page.getByRole('slider', { name: '语速', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  check('Speed responds to keyboard', await page.getByRole('slider', { name: '语速', exact: true }).inputValue() === '1.1');
  await page.getByRole('slider', { name: '音调', exact: true }).focus();
  await page.keyboard.press('ArrowLeft');
  check('Pitch responds to keyboard', await page.getByRole('slider', { name: '音调', exact: true }).inputValue() === '0.9');
  await page.getByRole('slider', { name: '音量', exact: true }).focus();
  await page.keyboard.press('End');
  check('Volume can reach upper bound', await page.getByRole('slider', { name: '音量', exact: true }).inputValue() === '100');
  const text = page.getByRole('textbox', { name: '输入文字', exact: true });
  for (const [name, title, fragment] of [['趣味绕口令','吃葡萄','吃葡萄'],['英语角','A sunny day','The sun'],['小故事','月亮邮递员','小熊'],['古诗词','春晓','春眠不觉晓']]) {
    const previous = await text.inputValue();
    await page.getByRole('button', { name, exact: true }).click();
    check(`Browsing ${name} preserves edited text`, await text.inputValue() === previous);
    const group = page.getByRole('group', { name: `${name}篇目`, exact: true });
    check(`${name} offers three materials`, await group.getByRole('button').count() === 3);
    await group.getByRole('button', { name: new RegExp(title) }).click();
    check(`Choosing ${title} updates editor`, (await text.inputValue()).includes(fragment));
    check('Selected material is marked', await group.locator('[aria-pressed=true]').count() === 1);
    await text.fill('我自己写的句子。');
    check('Editing removes stale selected material', await group.locator('[aria-pressed=true]').count() === 0);
  }
  await text.fill('测'.repeat(120));
  check('Pasted text limited to 100 characters', (await text.inputValue()).length === 100 && await page.getByText('100/100 字', { exact: true }).isVisible());
  await text.fill('😀'.repeat(101));
  check('Unicode characters do not split at limit', Array.from(await text.inputValue()).length === 100 && !(await text.inputValue()).includes('�'));
  await page.getByRole('button', { name: '清空文字', exact: true }).click();
  check('Text can be cleared', await text.inputValue() === '' && await page.getByText('0/100 字', { exact: true }).isVisible());
  await page.getByRole('button', { name: '重置全部', exact: true }).click();
  check('Reset restores all defaults', (await text.inputValue()).startsWith('床前明月光') && await page.getByLabel('选择音色', { exact: true }).inputValue() === 'Cherry' && await page.getByRole('slider', { name: '语速', exact: true }).inputValue() === '1' && await page.getByRole('slider', { name: '音调', exact: true }).inputValue() === '1' && await page.getByRole('slider', { name: '音量', exact: true }).inputValue() === '75');
  await page.reload();
  await page.getByRole('heading', { name: '语音合成体验', exact: true }).waitFor();
  check('Direct route survives reload', page.url().endsWith('#/tts'));
  await page.setViewportSize({ width: 390, height: 844 });
  check('Mobile page has no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(artifacts, 'mobile.png'), fullPage: true });
  await page.getByRole('button', { name: '英语角', exact: true }).click();
  await page.getByRole('group', { name: '英语角篇目', exact: true }).getByRole('button', { name: /My little garden/ }).click();
  check('Mobile material selection works', (await text.inputValue()).startsWith('This is my little garden'));
  available = true;
  await page.getByRole('button', {name:'重新检查', exact:true}).click();
  await page.waitForFunction(() => !document.querySelector('.tts-player-actions .ant-btn-primary')?.disabled);
  await page.getByLabel('选择音色', {exact:true}).selectOption('Aiden');
  await page.getByRole('slider', {name:'语速',exact:true}).focus(); await page.keyboard.press('ArrowRight');
  await page.getByRole('slider', {name:'音调',exact:true}).focus(); await page.keyboard.press('ArrowLeft');
  await page.getByRole('slider', {name:'音量',exact:true}).focus(); await page.keyboard.press('Home');
  await page.getByRole('button', {name:'合成语音',exact:true}).click();
  await page.getByLabel('合成音频', {exact:true}).waitFor();
  check('All settings sent with selected voice', submitted.at(-1).voice === 'Aiden' && submitted.at(-1).speed === 1.1 && submitted.at(-1).pitch === .9 && submitted.at(-1).volume === 0);
  await page.getByRole('button', {name:'播放语音',exact:true}).click();
  check('Generated audio can play', await page.locator('audio').evaluate(a=>!a.paused));
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', {name:'下载音频',exact:true}).click();
  check('Audio download filename matches voice', (await downloadEvent).suggestedFilename() === 'speech-Aiden.wav');
  await text.fill('新的文字');
  check('Changed text blocks stale playback/download', await page.locator('audio').count() === 0 && await page.getByRole('button',{name:'下载音频',exact:true}).isDisabled());
  await page.getByText('文字或声音设置已改变，请重新合成。',{exact:true}).waitFor();
  mode = 'failure'; await page.getByRole('button',{name:'合成语音',exact:true}).click();
  await page.getByText('测试：合成请求受限',{exact:true}).waitFor();
  check('Provider error is shown without fake success', await page.locator('audio').count() === 0);
  mode = 'bad-audio'; await page.getByRole('button',{name:'合成语音',exact:true}).click();
  await page.getByText('合成音频格式异常，请重试。',{exact:true}).waitFor();
  check('Invalid audio rejected', await page.locator('audio').count() === 0);
  mode = 'delayed';
  let pending = page.waitForRequest('**/api/tts/synthesize');
  await page.getByRole('button',{name:'合成语音',exact:true}).click(); await pending;
  check('Busy state disables text and duplicate submission', await text.isDisabled() && await page.getByRole('button',{name:'合成语音',exact:true}).isDisabled());
  await page.getByRole('button',{name:'取消等待',exact:true}).click();
  await page.waitForTimeout(1750);
  check('Cancelled response never replaces audio', await page.locator('audio').count() === 0);
  pending = page.waitForRequest('**/api/tts/synthesize');
  await page.getByRole('button',{name:'合成语音',exact:true}).click(); await pending;
  await page.getByRole('button',{name:'重置全部',exact:true}).click();
  await page.waitForTimeout(1750);
  check('Reset discards in-flight result', await page.locator('audio').count() === 0 && (await text.inputValue()).startsWith('床前'));
  mode = 'success'; await page.getByRole('button',{name:'合成语音',exact:true}).click();
  await page.getByLabel('合成音频',{exact:true}).waitFor();
  const oldUrl = await page.locator('audio').getAttribute('src');
  await page.getByRole('slider',{name:'语速',exact:true}).focus(); await page.keyboard.press('ArrowRight');
  check('Slider changes require new synthesis', await page.getByRole('button',{name:'播放语音',exact:true}).isDisabled());
  await page.getByRole('button',{name:'合成语音',exact:true}).click();
  await page.getByLabel('合成音频',{exact:true}).waitFor();
  check('Old audio URL is released after regeneration', await page.evaluate(async url => {try {await fetch(url);return false;} catch {return true;}},oldUrl));
  await page.setViewportSize({width:1440,height:950});
  await page.screenshot({path:join(artifacts,'generated-desktop.png'),fullPage:true});
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await page.getByRole('button', { name: '打开语音识别体验', exact: true }).click();
  await page.getByRole('heading', { name: '语音识别', exact: true }).waitFor();
  check('Existing speech recognition entry still works', page.url().endsWith('#/speech'));
  check('All API responses intercepted; no production writes', writes.length === 0);
  check('No browser runtime errors', errors.length === 0);
  const result = { passed: checks.length, checks, errors };
  writeFileSync(join(artifacts, 'results.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally {
  await browser?.close();
  await new Promise(resolve => server.httpServer.close(resolve));
}
