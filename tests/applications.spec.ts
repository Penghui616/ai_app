import { test, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
test.use({ actionTimeout: 10000, reducedMotion: 'reduce' });

test('application navigation, history routing and separate assistant roles', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '应用选择', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: /^应用体验/ })).toBeVisible();
  await expect(page.getByRole('heading', { name: /^应用实验/ })).toBeVisible();
  await expect(page.getByRole('button', { name: '语音识别体验，开发中', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '应用实验', exact: true }).click();
  await expect(page.getByRole('button', { name: '应用实验', exact: true })).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button', { name: '应用体验', exact: true }).click();
  await page.evaluate(() => window.scrollTo(0,0));
  await mkdir('qa', { recursive: true });
  await page.screenshot({ path: 'qa/application-hub.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '应用导航助手 演示', exact: true }).click();
  await page.getByRole('button', { name: '体验和训练的区别', exact: true }).click();
  await expect(page.locator('.assistant-bubble').last()).toContainText('允许你自定义类别');
  await page.getByRole('button', { name: '去图像体验', exact: true }).click();
  await expect(page).toHaveURL(/#\/experience$/);
  await expect(page.getByRole('heading', { name: '给 AI 一张图片，看看它的判断' })).toBeVisible();
  await page.getByRole('button', { name: '图像体验助手 演示', exact: true }).click();
  await expect(page.locator('.assistant-message')).toHaveCount(0);
  await page.getByRole('button', { name: '分数代表什么', exact: true }).click();
  await expect(page.locator('.assistant-bubble').last()).toContainText('只是固定的界面演示数值');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '返回应用选择', exact: true }).click();
  await page.getByRole('button', { name: '应用导航助手 演示', exact: true }).click();
  await expect(page.locator('.assistant-message')).toHaveCount(2);
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '打开图像分类实验', exact: true }).click();
  await expect(page.getByTestId('class-card')).toHaveCount(2);
  const category = page.getByRole('textbox', { name: '类别 1 名称', exact: true });
  await category.fill('保留原工作台'); await category.press('Enter');
  await page.getByRole('button', { name: '应用选择', exact: true }).click();
  await page.goBack();
  await expect(category).toHaveValue('保留原工作台');
  await page.reload();
  await expect(category).toHaveValue('保留原工作台');
  expect(errors).toEqual([]);
});

test('experience demo validation, local records, notes, reload, export and deletion', async ({ page }) => {
  await page.goto('/#/experience');
  const demo = page.getByRole('button', { name: '查看演示结果', exact: true });
  await expect(demo).toBeDisabled();
  await page.getByTestId('experience-upload').locator('input[type=file]').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image') });
  await expect(page.getByText('请上传 JPG、PNG 或 WebP 格式的图片。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '使用示例插画', exact: true }).click();
  await expect(demo).toBeEnabled(); await demo.click();
  await expect(page.locator('.experience-record')).toHaveCount(1);
  await expect(page.getByText('固定演示值，与图片内容无关。', { exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: '我的观察与猜想', exact: true }).fill('换个角度会不会影响结果？');
  await page.getByRole('button', { name: '保存观察', exact: true }).click();
  await expect(page.locator('.experience-record')).toContainText('换个角度会不会影响结果？');
  await expect(page.locator('.ant-message-notice')).toHaveCount(0, { timeout: 10000 });
  await page.screenshot({ path: 'qa/image-experience.png', fullPage: true, animations: 'disabled' });
  await page.reload();
  await expect(page.locator('.experience-record')).toHaveCount(1);
  await page.locator('.experience-record-open').click();
  await expect(page.getByRole('textbox', { name: '我的观察与猜想', exact: true })).toHaveValue('换个角度会不会影响结果？');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出演示记录', exact: true }).click();
  const download = await downloadEvent;
  const result = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(result.isMock).toBe(true); expect(result.records).toHaveLength(1); expect(result.records[0].image).toBeUndefined();
  expect(result.records[0].note).toContain('换个角度');
  await page.getByRole('button', { name: '移除体验图片', exact: true }).click();
  await expect(demo).toBeDisabled();
  await expect(page.locator('.experience-top-result')).toHaveCount(0);
  await page.locator('.experience-record').getByRole('button', { name: /删除体验记录/ }).click();
  await page.getByRole('button', { name: '删除记录', exact: true }).click();
  await expect(page.locator('.experience-record')).toHaveCount(0);
  await page.reload(); await expect(page.locator('.experience-record')).toHaveCount(0);
});

