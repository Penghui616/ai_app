import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
test.use({ actionTimeout: 10000, reducedMotion: 'reduce' });

test('assistant uses live sample metadata, keeps immutable evidence and isolates project history', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByTestId('class-card')).toHaveCount(2);
  const initialTitle = await page.locator('h1').innerText();
  await page.getByRole('button', { name: '实验助手 演示', exact: true }).click();
  const panel = page.locator('.experiment-assistant');
  await expect(panel.getByText('助手演示 · 尚未接入 AI')).toBeVisible();
  await expect(panel.getByTestId('assistant-context')).toContainText('0 张图片');
  await panel.getByRole('button', { name: '检查样本', exact: true }).click();
  await expect(panel.locator('.assistant-bubble').last()).toContainText('还有 2 个类别没有图片');
  await panel.locator('summary').last().click();
  await expect(panel.locator('details').last()).toContainText('类别1：0 张');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('textbox', { name: '类别 1 名称', exact: true }).fill('水果');
  await page.getByRole('textbox', { name: '类别 1 名称', exact: true }).press('Enter');
  await page.getByRole('button', { name: '帮我检查样本', exact: true }).click();
  await expect(panel.getByRole('textbox', { name: '向实验助手提问' })).toHaveValue('帮我检查当前的样本分布。');
  await panel.getByRole('button', { name: '发送问题', exact: true }).click();
  await expect(panel.locator('.assistant-bubble').last()).toContainText('“水果”：0 张');
  await expect(panel.locator('details').first()).toContainText('类别1：0 张');
  await panel.getByRole('button', { name: '测试建议', exact: true }).click();
  await expect(panel.locator('.assistant-bubble').last()).toContainText('单张预测分数不等于整体准确率');
  await panel.getByRole('textbox', { name: '向实验助手提问' }).fill('随便一个未接入的问题');
  await panel.getByRole('textbox', { name: '向实验助手提问' }).press('Enter');
  await expect(panel.locator('.assistant-bubble').last()).toContainText('尚未连接大模型');
  await page.reload();
  await page.getByRole('button', { name: '实验助手 演示', exact: true }).click();
  await expect(panel.locator('.assistant-message')).toHaveCount(8);
  await mkdir('qa', { recursive: true });
  await page.screenshot({ path: 'qa/assistant-desktop.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '新建项目', exact: true }).first().click();
  await page.getByRole('textbox', { name: '项目名称', exact: true }).fill('独立辅导项目');
  await page.getByRole('button', { name: '创建项目', exact: true }).click();
  await expect(page.getByRole('heading', { name: '独立辅导项目', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '实验助手 演示', exact: true }).click();
  await expect(panel.locator('.assistant-message')).toHaveCount(0);
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '我的项目', exact: true }).click();
  await page.getByRole('button', { name: initialTitle, exact: true }).click();
  await page.getByRole('button', { name: '实验助手 演示', exact: true }).click();
  await expect(panel.locator('.assistant-message')).toHaveCount(8);
  await panel.getByRole('button', { name: '清空辅导记录', exact: true }).click();
  await page.getByRole('button', { name: '清空', exact: true }).click();
  await expect(panel.locator('.assistant-message')).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: '实验助手 演示', exact: true }).click();
  await expect(panel.locator('.assistant-message')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('mobile assistant remains usable and reports blocked storage', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) {
      if (key.startsWith('vision-lab:assistant:')) throw new DOMException('Full', 'QuotaExceededError');
      return original.call(this, key, value);
    };
  });
  await page.goto('/');
  await page.getByRole('button', { name: '实验助手 演示', exact: true }).click();
  const panel = page.locator('.experiment-assistant');
  await panel.getByRole('textbox', { name: '向实验助手提问' }).fill('复制同一张图片可以吗？');
  await panel.getByRole('button', { name: '发送问题', exact: true }).click();
  await expect(panel.locator('.assistant-bubble').last()).toContainText('不会增加新的角度');
  await expect(panel.getByText(/对话暂未保存/)).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const inputBox = await panel.getByRole('textbox', { name: '向实验助手提问' }).boundingBox();
  expect(inputBox!.y + inputBox!.height).toBeLessThanOrEqual(844);
  await page.screenshot({ path: 'qa/assistant-mobile.png', fullPage: false, animations: 'disabled' });
  await page.keyboard.press('Escape');
  await expect(panel.getByRole('textbox', { name: '向实验助手提问' })).not.toBeVisible();
});
